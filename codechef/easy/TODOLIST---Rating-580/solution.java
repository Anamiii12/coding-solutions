import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
		// your code goes here
		Scanner sc =new Scanner(System.in);
		int T =sc.nextInt();

		while(T>0){
		    
		    int N =sc.nextInt();
		    int c=0;
		    for(int i =0;i<N;i++){
		        int diff =sc.nextInt();
		    
		    if(diff>=1000){
		        c++;
		   }

		}
		System.out.println(c);
T--;
	}
}}
